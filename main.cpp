#include <iostream>
#include <cmath>
#include <iomanip>

#ifdef _WIN32
#include <windows.h>
#endif

using namespace std;

int main()
{
    // Налаштування кодування для коректного відображення українських символів у консолі Windows
#ifdef _WIN32
    SetConsoleCP(65001);
    SetConsoleOutputCP(65001);
#endif

    // Налаштування формату виведення чисел із плаваючою комою (до 4 знаків після коми)
    cout << fixed << setprecision(4);

    cout << "================================================================" << endl;
    cout << "  Лабораторна робота №1: Введення-виведення даних в C++" << endl;
    cout << "  Варіант 42 (Завдання 1: задачі 1 та 2)" << endl;
    cout << "================================================================\n" << endl;

    // =========================================================================
    // ЗАВДАННЯ 1. ЗАДАЧА 1 (Begin42)
    // Умова: Дано діагоналі ромба d1 і d2. Знайти площу: S = (d1 * d2) / 2.
    // Вхідні дані: d1, d2 - дійсні числа, d1 > 0, d2 > 0.
    // Вихідні дані: S - площа ромба, дійсне число.
    // =========================================================================

    // Виведення повідомлення про початок виконання першої задачі
    cout << "----------------------------------------------------------------" << endl;
    cout << "  ПОЧАТОК ВИКОНАННЯ: Задача 1 (Begin42)" << endl;
    cout << "  Тема: Обчислення площі ромба за його діагоналями" << endl;
    cout << "----------------------------------------------------------------" << endl;

    // Декларація змінних для задачі 1
    double d1 = 0.0; // Перша діагональ ромба
    double d2 = 0.0; // Друга діагональ ромба
    double S = 0.0;  // Площа ромба

    // Введення значень змінних із перевіркою коректності (дійсні числа > 0)
    while (true)
    {
        cout << "Введіть довжину першої діагоналі d1 (d1 > 0): ";
        if (cin >> d1 && d1 > 0)
        {
            break;
        }
        cout << "Помилка! Довжина діагоналі повинна бути додатним дійсним числом. Спробуйте ще раз.\n";
        cin.clear();
        cin.ignore(10000, '\n');
    }

    while (true)
    {
        cout << "Введіть довжину другої діагоналі d2 (d2 > 0): ";
        if (cin >> d2 && d2 > 0)
        {
            break;
        }
        cout << "Помилка! Довжина діагоналі повинна бути додатним дійсним числом. Спробуйте ще раз.\n";
        cin.clear();
        cin.ignore(10000, '\n');
    }

    // Розрахунок результату задачі 1 за формулою: S = (d1 * d2) / 2
    S = (d1 * d2) / 2.0;

    // Виведення результату задачі 1 з текстовим поясненням
    cout << "\nРезультати розрахунку Задачі 1:" << endl;
    cout << "-> Діагональ d1 = " << d1 << endl;
    cout << "-> Діагональ d2 = " << d2 << endl;
    cout << "-> Площа ромба S = (d1 * d2) / 2 = " << S << endl;
    cout << "----------------------------------------------------------------\n" << endl;


    // =========================================================================
    // ЗАВДАННЯ 1. ЗАДАЧА 2 (Begin42)
    // Умова: Дано діагоналі ромба d1 і d2.
    //        Знайти довжину сторони ромба a та його периметр P.
    // Вхідні дані: d1, d2 - дійсні числа, d1 > 0, d2 > 0.
    // Вихідні дані: a - довжина сторони, P - периметр, h - висота (дійсні числа).
    // Алгоритм:
    // 1) Оскільки діагоналі ромба перетинаються під прямим кутом і діляться навпіл,
    //    за теоремою Піфагора: a = sqrt((d1/2)^2 + (d2/2)^2) = sqrt(d1^2 + d2^2) / 2;
    // 2) Периметр ромба: P = 4 * a;
    // 3) Висота ромба (за формулою S = a * h): h = S / a.
    // =========================================================================

    // Виведення повідомлення про початок виконання другої задачі
    cout << "----------------------------------------------------------------" << endl;
    cout << "  ПОЧАТОК ВИКОНАННЯ: Задача 2 (Begin42)" << endl;
    cout << "  Тема: Знаходження сторони, периметра та висоти ромба" << endl;
    cout << "----------------------------------------------------------------" << endl;

    // Декларація змінних для задачі 2
    double a = 0.0; // Сторона ромба
    double P = 0.0; // Периметр ромба
    double h = 0.0; // Висота ромба

    char choice = 'y';
    cout << "Використати діагоналі d1 = " << d1 << " та d2 = " << d2
         << " з попередньої задачі? (y/n): ";
    cin >> choice;

    if (choice == 'n' || choice == 'N')
    {
        // Введення нових значень діагоналей
        while (true)
        {
            cout << "Введіть нову довжину діагоналі d1 (d1 > 0): ";
            if (cin >> d1 && d1 > 0)
            {
                break;
            }
            cout << "Помилка! Довжина діагоналі повинна бути додатним числом.\n";
            cin.clear();
            cin.ignore(10000, '\n');
        }

        while (true)
        {
            cout << "Введіть нову довжину діагоналі d2 (d2 > 0): ";
            if (cin >> d2 && d2 > 0)
            {
                break;
            }
            cout << "Помилка! Довжина діагоналі повинна бути додатним числом.\n";
            cin.clear();
            cin.ignore(10000, '\n');
        }

        // Перераховуємо площу ромба для нових діагоналей
        S = (d1 * d2) / 2.0;
    }

    // Розрахунок результатів задачі 2
    // Сторона ромба за теоремою Піфагора
    a = sqrt((d1 / 2.0) * (d1 / 2.0) + (d2 / 2.0) * (d2 / 2.0));

    // Периметр ромба: P = 4 * a
    P = 4.0 * a;

    // Висота ромба: h = S / a
    h = S / a;

    // Виведення результатів задачі 2 з текстовим поясненням
    cout << "\nРезультати розрахунку Задачі 2:" << endl;
    cout << "-> Діагоналі ромба: d1 = " << d1 << ", d2 = " << d2 << endl;
    cout << "-> Сторона ромба a = sqrt((d1/2)^2 + (d2/2)^2) = " << a << endl;
    cout << "-> Периметр ромба P = 4 * a = " << P << endl;
    cout << "-> Висота ромба h = S / a = " << h << endl;
    cout << "----------------------------------------------------------------" << endl;

    cout << "\nПрограму успішно завершено." << endl;
    return 0;
}
